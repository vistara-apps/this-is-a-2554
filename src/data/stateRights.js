// Helper function to get state data with fallback
export const getStateRights = (stateName, scenario = 'trafficStop') => {
  const stateData = stateRightsData[stateName];
  
  if (!stateData) {
    // Fallback to California data if state not found
    return stateRightsData['California'][scenario] || stateRightsData['California']['trafficStop'];
  }
  
  return stateData[scenario] || stateData['trafficStop'];
};

// Get all available states
export const getAvailableStates = () => {
  return Object.keys(stateRightsData).sort();
};

// Check if a state has data
export const hasStateData = (stateName) => {
  return Boolean(stateRightsData[stateName]);
};

// Get scenarios available for a state
export const getStateScenarios = (stateName) => {
  const stateData = stateRightsData[stateName];
  if (!stateData) return [];
  
  return Object.keys(stateData);
};

